/**
 * Builds a product's documentation site into _site/:
 *
 *   /                 the landing page (site/landing.md)
 *   /diagrams/        the gallery, and every diagram page as Archify rendered it
 *   /adr/             the decisions, each rendered from adr/*.md
 *   /roadmap.html     ROADMAP.md
 *   /ontology/        the T-Box reference (scripts/ontology.mjs) and its Turtle,
 *                     when shared.json has an "ontology"
 *   /site.json        what the site holds, for the index at docs.dlab5.net
 *
 * Plain HTML and one stylesheet, light and dark, no outside resources. Links
 * are relative, so the same pages work at the root of the product's own
 * domain and under docs.dlab5.net/<domain>/<slug>/, which the aggregator
 * (d-lab-5/d-lab-5.github.io) builds with --base. With an own domain, every
 * page names it as canonical; CNAME is written only for a build of its own.
 *
 *   node scripts/site.mjs [--out _site] [--base /<domain>/<slug>/]
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { marked } from "marked";
import { config } from "./config.mjs";
import { REPO, adrs, groups, size, sources } from "./diagrams.mjs";
import { ONTOLOGY, ontologyHtml, readOntology } from "./ontology.mjs";

const arg = (name, fallback) => (process.argv.includes(name) ? process.argv[process.argv.indexOf(name) + 1] : fallback);
const OUT = resolve(REPO, arg("--out", "_site"));
const BASE = (() => {
  const b = arg("--base", "/");
  if (!/^\/([a-z0-9][a-z0-9-]*\/)*$/.test(b)) throw new Error(`--base is a path like /digitalhome/mediathek/, not ${b}`);
  return b;
})();
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const read = (p) => readFileSync(join(REPO, p), "utf8");
const TYPE_WORD = {
  sequence: "who calls whom, in order", lifecycle: "the states something passes through",
  dataflow: "where the data goes", architecture: "what the parts are", workflow: "the steps",
  erd: "the tables", class: "the types", tree: "what contains what",
  timeline: "when things happened", waterfall: "where the time went",
};

/** A Markdown document as HTML, with links to other .md files turned into their pages. */
function md(text) {
  const html = marked.parse(text, { gfm: true });
  return html.replace(/href="([^"#:]+)\.md(#[^"]*)?"/g, (_, p, h) => `href="${p}.html${h || ""}"`);
}

const nav = () => [["", "Home"], ["diagrams/", "Diagrams"], ["adr/", "Decisions"], ["roadmap.html", "Roadmap"],
  ...(config().ontology ? [["ontology/", "Ontology"]] : [])];

/** A page in the site's frame; `depth` is how many folders down it sits. */
function page({ title, body, depth = 0, here = "", up = "../".repeat(depth) }) {
  const c = config();
  const links = nav().map(([href, word]) => `<a href="${up}${href}"${href === here ? ' aria-current="page"' : ""}>${word}</a>`).join("");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)} · ${esc(c.product)} docs</title>
<link rel="stylesheet" href="${up}assets/site.css">
<!-- generated by scripts/site.mjs: edit the Markdown or the diagram sources instead -->
</head><body>
<header class="top"><a class="brand" href="${up}">${esc(c.product)} <span>docs</span></a><nav>${links}</nav></header>
<main>${body}</main>
<footer>${esc(c.texts.footer)} · <a href="${c.repo_url}">source of these pages</a> · documents and diagrams CC BY 4.0, scripts MIT</footer>
</body></html>
`;
}

function card(s, link, adrHref) {
  const title = link?.title || s.data.meta?.title || s.name;
  const about = link?.about || TYPE_WORD[s.type] || "";
  const parts = (s.data.cards || []).map((c) => c.title).filter(Boolean);
  const search = [title, about, s.type, s.name, ...parts].join(" ").toLowerCase();
  return `<article class="card" data-type="${esc(s.type)}" data-search="${esc(search)}">
    <a class="card__main" href="${esc(s.name)}.html"><span class="kind">${esc(s.type)}</span><h3>${esc(title)}</h3>${about ? `<p>${esc(about)}</p>` : ""}
    <p class="size">${esc(size(s.data))}${parts.length ? ` · ${esc(parts.join(", "))}` : ""}</p></a>
    ${adrHref ? `<a class="card__adr" href="${esc(adrHref)}">the decision</a>` : ""}</article>`;
}

function gallery() {
  const all = sources();
  const byName = new Map(all.map((s) => [s.name, s]));
  const types = new Map();
  all.forEach((s) => types.set(s.type, (types.get(s.type) || 0) + 1));
  const sections = groups().map((g) => {
    const items = g.links.filter((l) => byName.has(l.name));
    if (!items.length) return "";
    const adrHref = g.adr ? `../adr/${g.adr.stem}.html` : "";
    return `<section class="group" id="${esc(g.id)}"><h2>${esc(g.heading)}</h2>
      ${g.adr ? `<p class="meta">${esc(g.adr.status)} · <a href="${esc(adrHref)}">read the decision</a></p>` : ""}
      ${g.lead ? `<p class="lead">${esc(g.lead)}</p>` : ""}
      <div class="grid">${items.map((l) => card(byName.get(l.name), l, adrHref)).join("")}</div></section>`;
  }).join("");
  const buttons = `<button type="button" data-type="" aria-pressed="true">all ${all.length}</button>`
    + [...types].sort().map(([t, n]) => `<button type="button" data-type="${esc(t)}" aria-pressed="false">${esc(t)} ${n}</button>`).join("");
  return page({ title: "Diagrams", depth: 1, here: "diagrams/", body: `
<h1>Diagrams</h1>
<p class="lead">${all.length} interactive drawings: ${esc(config().texts.diagrams)}. Each one zooms, plays its flow, switches between dark and light, and exports an image or SVG.</p>
<div class="bar"><input id="q" type="search" placeholder="Filter: title, part, type…" aria-label="Filter the diagrams">${buttons}</div>
${sections}<p id="none" class="empty" hidden>No diagram matches the filter.</p>
<script>${GALLERY_JS}</script>` });
}

function decisions() {
  const list = adrs();
  const pages = list.map((a) => {
    let text = read(`adr/${a.file}`);
    const body = md(text);
    const prev = list[list.indexOf(a) - 1], next = list[list.indexOf(a) + 1];
    const pn = `<nav class="pn">${prev ? `<a href="${prev.stem}.html">← ${esc(prev.heading)}</a>` : "<span></span>"}${next ? `<a href="${next.stem}.html">${esc(next.heading)} →</a>` : ""}</nav>`;
    return [a.stem, page({ title: a.heading, depth: 1, here: "adr/", body: `<p class="crumbs"><a href="./">Decisions</a></p><article class="doc">${body}</article>${pn}` })];
  });
  const rows = list.map((a) => `<tr><td><a href="${a.stem}.html">${esc(a.heading)}</a>${a.links.length ? ` <small class="tag">${a.links.length} diagram${a.links.length > 1 ? "s" : ""}</small>` : ""}</td><td><small>${esc(a.status)}</small></td></tr>`).join("");
  const index = page({ title: "Decisions", depth: 1, here: "adr/", body: `
<h1>Decisions</h1>
<p class="lead">${esc(config().texts.decisions)}</p>
<table class="adrs"><tr><th>Decision</th><th>Status</th></tr>${rows}</table>` });
  return { pages, index };
}

function landing() {
  const counts = { diagrams: sources().length, adrs: adrs().length };
  const text = read("site/landing.md").replace(/\{(diagrams|adrs)\}/g, (_, k) => String(counts[k]));
  return page({ title: "Home", here: "", body: `<article class="doc landing">${md(text)}</article>` });
}

/** With an own domain, a page names its address there, so the two copies do not compete. */
function canonical(rel, html) {
  const own = config().own_domain;
  if (!own || !html.includes("</head>")) return html;
  const path = rel.replace(/(^|\/)index\.html$/, "$1");
  return html.replace("</head>", `<link rel="canonical" href="https://${own}/${esc(path)}">\n</head>`);
}

function write(rel, html) {
  const to = join(OUT, rel);
  mkdirSync(dirname(to), { recursive: true });
  writeFileSync(to, rel.endsWith(".html") ? canonical(rel, html) : html);
}

function commit() {
  try { return execFileSync("git", ["rev-parse", "HEAD"], { cwd: REPO, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); }
  catch { return ""; }
}

export function buildSite() {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  cpSync(join(REPO, "site", "site.css"), join(OUT, "assets", "site.css"));
  write("index.html", landing());
  write("diagrams/index.html", gallery());
  for (const s of sources()) if (existsSync(s.page)) write(`diagrams/${s.name}.html`, readFileSync(s.page, "utf8"));
  const d = decisions();
  write("adr/index.html", d.index);
  for (const [stem, html] of d.pages) write(`adr/${stem}.html`, html);
  const roadmap = existsSync(join(REPO, "ROADMAP.md")) ? md(read("ROADMAP.md")) : "<h1>Roadmap</h1><p>No roadmap yet.</p>";
  write("roadmap.html", page({ title: "Roadmap", here: "roadmap.html", body: `<article class="doc">${roadmap}</article>` }));
  const c = config();
  let classes = 0;
  if (c.ontology) {
    const o = readOntology();
    classes = o.classes.length;
    write("ontology/index.html", page({ title: "Ontology", depth: 1, here: "ontology/", body: `<h1>${esc(c.texts.ontology_title)}</h1>${ontologyHtml(o)}` }));
    for (const f of o.files) { mkdirSync(join(OUT, "ontology", dirname(f)), { recursive: true }); cpSync(join(ONTOLOGY, f), join(OUT, "ontology", f)); }
  }
  // served for any missing path, at any depth: its links start from the site's base
  write("404.html", page({ title: "Not found", up: BASE, body: `<h1>Not here</h1><p>That page does not exist. <a href="${BASE}">Start from the home page.</a></p>` }));
  if (c.own_domain && BASE === "/") writeFileSync(join(OUT, "CNAME"), c.own_domain + "\n");
  writeFileSync(join(OUT, ".nojekyll"), "");
  const manifest = { product: c.product, slug: c.slug, domain: c.domain, description: c.description, repo: c.repo,
    own_domain: c.own_domain || null, commit: commit() || null,
    counts: { diagrams: sources().length, adrs: d.pages.length, classes } };
  writeFileSync(join(OUT, "site.json"), JSON.stringify(manifest, null, 2) + "\n");
  return { out: OUT, pages: 5 + (c.ontology ? 1 : 0) + d.pages.length + sources().length };
}

const GALLERY_JS = `
const q=document.getElementById("q"),buttons=[...document.querySelectorAll(".bar button")];let type="";
function apply(){const s=q.value.trim().toLowerCase();let shown=0;
for(const c of document.querySelectorAll("article.card")){const hide=(type&&c.dataset.type!==type)||(s&&!c.dataset.search.includes(s));c.hidden=!!hide;if(!hide)shown++;}
for(const g of document.querySelectorAll("section.group"))g.hidden=!g.querySelector("article.card:not([hidden])");
for(const b of buttons)b.setAttribute("aria-pressed",String(b.dataset.type===type));
document.getElementById("none").hidden=shown>0;}
for(const b of buttons)b.addEventListener("click",()=>{type=b.dataset.type;apply();});
q.addEventListener("input",apply);
`;

if (process.argv[1] && process.argv[1].endsWith("site.mjs")) {
  const r = buildSite();
  console.log(`wrote ${r.pages} pages to ${r.out}`);
}
